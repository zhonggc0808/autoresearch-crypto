"""
LLM-powered hypothesis generator for GEPA reflective evolution.

Replaces the 8 hardcoded hypothesis templates with dynamic,
context-aware hypotheses generated by an LLM (Anthropic Claude)
based on recent experiment logs, agent states, and blind spots.

Usage::

    from dex.llm_hypothesis import LLMHypothesisGenerator

    gen = LLMHypothesisGenerator(api_key="...", model="claude-sonnet-4-6")
    new_hypotheses = gen.generate(
        experiments=engine.experiment_logs[-10:],
        agents=agents,
        blind_spots=engine.blind_spots[-3:],
        n=4,
    )
    engine.inject_hypotheses(new_hypotheses)
"""

from __future__ import annotations

import json
import os
import time
from typing import Any, Dict, List, Optional

import requests

from dex.reflection import Hypothesis

# ---------------------------------------------------------------------------
# Prompt template (Chinese — matches the codebase language)
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """你是一个加密货币量化交易策略研究助手。你的任务是分析最近的策略实验日志，
发现失败模式，并提出新的、可验证的参数调整假设。

输出格式必须是严格 JSON：
```json
{
  "analysis": "对最近实验的简要分析（1-2句话）",
  "hypotheses": [
    {
      "text": "假设描述（中文，简洁明确）",
      "agent": "Alpha|Beta|Gamma|Delta",
      "param_changes": {"参数名": 新值, ...},
      "rationale": "为什么这个调整可能有效（1-2句话）",
      "blind_spot": "这个假设忽略了什么风险或市场条件"
    }
  ]
}
```

规则：
- 每个假设必须指定 target agent（Alpha/Beta/Gamma/Delta 之一）
- param_changes 中只包含要修改的参数，不需要全部列出
- 参数值必须是具体的数字或布尔值，不能是表达式
- 整数参数（window, atr_period, max_hold_bars, rsi_threshold, adx_threshold, grid_levels, trend_ma_period, rsi_period, rsi_low, rsi_high, ma_period）的值必须是整数
- 连续参数（std_dev, atr_multiplier, entry_zone, grid_spacing_pct, base_size, atr_spacing_mult, max_position, take_profit_pct, stop_loss_pct）可以是小数
- 布尔参数（use_adx, use_macd, use_volume, enable_short, use_resonance 等）必须是 true/false
- 提出 2-4 个不同的假设，针对不同的 agent
- 避免重复已经尝试过的参数组合
- 优先针对表现最差的 agent 提出假设
- 如果多个 agent 都存在类似问题，可以提出跨 agent 的通用假设"""


def build_user_prompt(
    experiments: List[Dict[str, Any]],
    agents: List[Dict[str, Any]],
    blind_spots: List[str],
    market_context: str = "",
) -> str:
    """Build a structured user prompt from recent experiment data.

    Args:
        experiments: List of recent experiment dicts with keys:
            agent, hypothesis, tried, score_before, score_after,
            sharpe_before, sharpe_after, ret_before, ret_after,
            dd_before, dd_after, reflection, edge_flags.
        agents: List of current agent states with keys:
            name, style, params, recent_score, revival_count.
        blind_spots: List of detected blind spots (strings).
        market_context: Optional market regime description.

    Returns:
        Formatted prompt string.
    """
    lines = ["## 当前市场环境", ""]
    if market_context:
        lines.append(market_context)
    else:
        lines.append("未知（未启用市场状态检测）")
    lines.append("")

    # Agent summary
    lines.append("## Agent 当前状态")
    lines.append("")
    lines.append("| Agent | 风格 | 最近评分 | 恢复次数 | 关键参数 |")
    lines.append("|-------|------|----------|----------|----------|")
    for a in agents:
        params_summary = ", ".join(
            f"{k}={v}" for k, v in sorted(a.get("params", {}).items())
            if k in {
                "window", "std_dev", "atr_multiplier", "max_hold_bars",
                "rsi_low", "rsi_high", "rsi_period", "ma_period",
                "entry_zone", "grid_spacing_pct", "grid_levels",
            }
        )
        lines.append(
            f"| {a['name']} | {a.get('style', '?')} | "
            f"{a.get('recent_score', 0):.3f} | {a.get('revival_count', 0)} | "
            f"{params_summary} |"
        )
    lines.append("")

    # Blind spots
    if blind_spots:
        lines.append("## 已发现的盲点")
        lines.append("")
        for bs in blind_spots:
            lines.append(f"- {bs}")
        lines.append("")

    # Experiment history
    lines.append("## 最近实验记录")
    lines.append("")
    for i, exp in enumerate(experiments[-10:], 1):
        lines.append(f"### 实验 {i}: {exp.get('agent', '?')}")
        lines.append(f"- 假设: {exp.get('hypothesis', '?')}")
        lines.append(f"- 参数变化: {exp.get('tried', '?')}")
        lines.append(
            f"- 结果: score {exp.get('score_before', 0):.3f} → "
            f"{exp.get('score_after', 0):.3f} "
            f"({exp.get('score_after', 0) - exp.get('score_before', 0):+.3f}), "
            f"sharpe {exp.get('sharpe_before', 0):.2f} → "
            f"{exp.get('sharpe_after', 0):.2f}, "
            f"DD {exp.get('dd_before', 0)*100:.1f}% → "
            f"{exp.get('dd_after', 0)*100:.1f}%"
        )
        flags = exp.get("edge_flags", [])
        if flags:
            lines.append(f"- 标记: {', '.join(flags)}")
        lines.append(f"- 反思: {exp.get('reflection', '?')[:120]}")
        lines.append("")

    lines.append("请分析以上实验记录，提出 3-4 个新的参数调整假设。")
    return "\n".join(lines)


